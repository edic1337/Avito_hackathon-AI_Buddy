-- Начальная схема RAG для PostgreSQL с установленным расширением pgvector.
-- Выполняется миграцией/администратором, а не при каждом запросе чата.
-- Повторный запуск не меняет уже существующие таблицы; следующие изменения — миграциями.

BEGIN;

CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;
CREATE SCHEMA IF NOT EXISTS rag;

-- Коллекция — корпус документов с едиными настройками подготовки векторов.
-- После загрузки данных модель/версию/чанкинг коллекции не изменяем:
-- создаём новую коллекцию и переиндексируем документы.
CREATE TABLE IF NOT EXISTS rag.collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (length(btrim(name)) > 0),
    embedding_model TEXT NOT NULL CHECK (length(btrim(embedding_model)) > 0),
    embedding_revision TEXT,
    embedding_dimension INTEGER NOT NULL DEFAULT 1024 CHECK (embedding_dimension = 1024),
    embedding_text_version INTEGER NOT NULL DEFAULT 1 CHECK (embedding_text_version > 0),
    query_prompt_name TEXT NOT NULL DEFAULT 'query',
    chunking_config JSONB NOT NULL CHECK (jsonb_typeof(chunking_config) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS rag.documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id BIGINT NOT NULL REFERENCES rag.collections(id) ON DELETE RESTRICT,
    -- Устойчивый логический ключ, например playbook/ds-skills.md.
    -- Не абсолютный путь D:\... с конкретного компьютера.
    source_key TEXT NOT NULL CHECK (length(btrim(source_key)) > 0),
    source_path TEXT,
    title TEXT NOT NULL CHECK (length(btrim(title)) > 0),
    content TEXT NOT NULL,
    source_url TEXT NOT NULL CHECK (length(btrim(source_url)) > 0),
    origin TEXT NOT NULL CHECK (origin IN ('public', 'synthetic')),
    min_role TEXT NOT NULL CHECK (min_role IN ('intern', 'buddy', 'manager')),
    team TEXT CHECK (team IS NULL OR length(btrim(team)) > 0),
    tags TEXT[] NOT NULL DEFAULT '{}',
    -- SHA-256 канонического JSON [title, content], считаем в Python.
    content_hash TEXT NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (collection_id, source_key)
);

CREATE TABLE IF NOT EXISTS rag.chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id BIGINT NOT NULL REFERENCES rag.documents(id) ON DELETE CASCADE,
    -- Порядок в документе. Совпадает с index в текущем JSON, начинается с 1.
    position INTEGER NOT NULL CHECK (position >= 1),
    section TEXT NOT NULL DEFAULT '',
    text TEXT NOT NULL CHECK (length(btrim(text)) > 0),
    -- Точная строка TextChunk.embedding_text(document.title).
    embedding_text TEXT NOT NULL CHECK (length(btrim(embedding_text)) > 0),
    token_count INTEGER NOT NULL CHECK (token_count > 0),
    -- SHA-256 embedding_text. Не UNIQUE: повторы допустимы в разных документах/позициях.
    content_hash TEXT NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    embedding public.vector(1024) NOT NULL,
    fts TSVECTOR GENERATED ALWAYS AS (
        to_tsvector('russian'::regconfig, embedding_text)
    ) STORED,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (doc_id, position),
    CHECK (public.vector_norm(embedding) BETWEEN 0.999 AND 1.001)
);

-- UNIQUE(collection_id, source_key) и UNIQUE(doc_id, position)
-- уже создают B-tree индексы для выбора коллекции и чанков документа.
CREATE INDEX IF NOT EXISTS rag_documents_access_idx
    ON rag.documents (collection_id, team, min_role)
    WHERE is_active;

CREATE INDEX IF NOT EXISTS rag_chunks_fts_idx ON rag.chunks USING gin (fts);

-- Векторный поиск пока точный, без HNSW. Добавляем его после замера задержек
-- и recall на реальном объёме, отдельно проверяя поиск с фильтрами доступа.

COMMIT;
